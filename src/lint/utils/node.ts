/** The version that is meant where none is said. */
const CURRENT_MAJOR = 24;

function compareName(name: string, buf: Uint8Array, start: number, end: number): number {
  const n = end - start;
  const m = name.length < n ? name.length : n;
  for (let i = 0; i < m; i++) {
    const a = name.charCodeAt(i);
    const b = buf[start + i] | 0;
    if (a !== b) return a < b ? -1 : 1;
  }
  return name.length === n ? 0 : name.length < n ? -1 : 1;
}

/** `is_builtin_module_in(specifier, [major, minor, patch])` */
export function isBuiltinModuleIn(buf: Uint8Array, start: number, end: number, major: number, minor: number, patch: number): boolean {
  let lo = 0;
  let hi = NAMES.length;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (compareName(NAMES[mid], buf, start, end) < 0) lo = mid + 1;
    else hi = mid;
  }
  if (lo >= NAMES.length || compareName(NAMES[lo], buf, start, end) !== 0) return false;
  const first = FIRST[lo];
  const count = COUNT[lo];
  for (let r = 0; r < count; r++) {
    const o = (first + r) * 6;
    const f0 = RANGES[o];
    const f1 = RANGES[o + 1];
    const f2 = RANGES[o + 2];
    const e0 = RANGES[o + 3];
    const e1 = RANGES[o + 4];
    const e2 = RANGES[o + 5];
    const afterFirst = major > f0 || (major === f0 && (minor > f1 || (minor === f1 && patch >= f2)));
    const beforeEnd = major < e0 || (major === e0 && (minor < e1 || (minor === e1 && patch < e2)));
    if (afterFirst && beforeEnd) return true;
  }
  return false;
}

/** `is_builtin_module(specifier)`: whether `buf[start, end)` is a module of Node.js, with or without `node:`. */
export function isBuiltinModule(buf: Uint8Array, start: number, end: number): boolean {
  return isBuiltinModuleIn(buf, start, end, CURRENT_MAJOR, 0, 0);
}
