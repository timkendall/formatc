// Generates src/sema/parser/unicode_tables.ts (ID_Start / ID_Continue ranges above U+007F) from node's Unicode data.
// Run: node tools/gen-unicode.ts
import * as fs from "node:fs";

function ranges(re: RegExp): number[] {
  const out: number[] = [];
  let start = -1;
  for (let c = 0x80; c <= 0x10ffff; c++) {
    if (c >= 0xd800 && c <= 0xdfff) {
      if (start >= 0) { out.push(start, c - 1); start = -1; }
      continue;
    }
    const ok = re.test(String.fromCodePoint(c));
    if (ok && start < 0) start = c;
    else if (!ok && start >= 0) { out.push(start, c - 1); start = -1; }
  }
  if (start >= 0) out.push(start, 0x10ffff);
  return out;
}
const idStart = ranges(/^\p{ID_Start}$/u);
const idPart = ranges(/^[\p{ID_Continue}‌‍]$/u);
let text = "// GENERATED by tools/gen-unicode.ts (node " + process.version + ", Unicode " + process.versions.unicode + "). Do not edit.\n";
text += "// Inclusive [lo, hi] code point pairs above U+007F. ASCII is handled by the byte tables of the lexer.\n";
function emit(name: string, a: number[]): void {
  text += "export const " + name + " = new Int32Array([\n";
  for (let i = 0; i < a.length; i += 12) text += "  " + a.slice(i, i + 12).join(", ") + ",\n";
  text += "]);\n";
}
emit("ID_START_RANGES", idStart);
emit("ID_PART_RANGES", idPart);
fs.writeFileSync(new URL("../src/sema/parser/unicode_tables.ts", import.meta.url), text);
console.log("ID_Start ranges:", idStart.length / 2, "ID_Part ranges:", idPart.length / 2);
