// Generates src/md/tables.ts from the Rust sources (vendor/bun/src/md) as compact strings that the TS port decodes at startup
// (cookbook section 8: big array literals cost seconds of build time).
// Run: node tools/md/gen-tables.mjs
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..", "..");
const md = path.join(root, "vendor/bun/src/md");

const helpers = fs.readFileSync(path.join(md, "helpers.rs"), "utf8");
const unicode = fs.readFileSync(path.join(md, "unicode.rs"), "utf8");
const entity = fs.readFileSync(path.join(md, "entity.rs"), "utf8");

function block(src, startRe) {
  const m = startRe.exec(src);
  if (!m) throw new Error("missing " + startRe);
  const open = src.indexOf("[", src.indexOf("=", m.index)); // after `= ` (skip the type's brackets)
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === "[") depth++;
    else if (src[i] === "]" && --depth === 0) return src.slice(open + 1, i);
  }
  throw new Error("unterminated " + startRe);
}
const b36 = (n) => n.toString(36);
const enc = (arr) => arr.map(b36).join(",");

// 1. punctuation ranges, delta coded: (lo - prevHi), (hi - lo)
const punct = block(helpers, /static UNICODE_PUNCTUATION_RANGES/);
const pr = [...punct.matchAll(/\[(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\]/g)].map((m) => [Number(m[1]), Number(m[2])]);
const pd = [];
let prev = 0;
for (const [lo, hi] of pr) { pd.push(lo - prev, hi - lo); prev = hi; }

// 2. case folding
const RS = 0x40000000, RE = 0x80000000;
const parseMap = (name) => {
  const body = block(unicode, new RegExp("static " + name + ": &\\[MapEntry\\]"));
  return [...body.matchAll(/(RANGE_START_FLAG|RANGE_END_FLAG)?\s*\|?\s*(0x[0-9a-fA-F]+)/g)]
    .filter((m) => m[0].trim() !== "")
    .map((m) => (m[1] === "RANGE_START_FLAG" ? RS : m[1] === "RANGE_END_FLAG" ? RE : 0) + Number(m[2]));
};
const parseData = (name) => {
  const body = block(unicode, new RegExp("static " + name + ": &\\[u32\\]"));
  return [...body.matchAll(/0x[0-9a-fA-F]+/g)].map((m) => Number(m[0]));
};
const folds = [];
for (const n of [1, 2, 3]) {
  const map = parseMap("FOLD_MAP_" + n), data = parseData("FOLD_MAP_" + n + "_DATA");
  if (data.length !== map.length * n) throw new Error("fold data " + n + " " + map.length + " " + data.length);
  // map entries: flags in the top bits -> split into (kind, cp)
  const flat = [];
  for (const e of map) { const kind = e >= RE ? 2 : e >= RS ? 1 : 0; flat.push(kind, e & 0xffffff); }
  folds.push(enc(flat) + "|" + enc(data));
}

// 3. entities
const namesBody = /static NAMES: &\[u8\] = b"((?:[^"\\]|\\.|\\\n)*)";/s.exec(entity)[1].replace(/\\\n/g, "");
if (namesBody.includes("\\")) throw new Error("escape in names");
const names = namesBody.split(";").slice(0, -1).map((n) => n + ";");
if (names.length !== 2125) throw new Error("names " + names.length);
const cps = [...block(entity, /static CODEPOINTS: \[u32; 2125\]/).matchAll(/\d+/g)].map((m) => Number(m[0]));
const second = [...block(entity, /static SECOND_CODEPOINTS/).matchAll(/\((\d+), (\d+)\)/g)].map((m) => [Number(m[1]), Number(m[2])]);
if (cps.length !== 2125) throw new Error("cps");
const HAS_SECOND = 2 ** 31;
const entCp = [];
const sec = new Map(second);
cps.forEach((c, i) => {
  const first = c >= HAS_SECOND ? c - HAS_SECOND : c;
  entCp.push(first, c >= HAS_SECOND ? sec.get(i) : 0);
});
// verify sortedness (byte order) so the binary search works
for (let i = 1; i < names.length; i++) if (!(names[i - 1] < names[i])) throw new Error("unsorted " + names[i]);

// 4. char::is_alphanumeric ranges of the pinned Rust (used by `:::name` directives), delta coded
const tmp = fs.mkdtempSync("/tmp/mdgen-");
fs.writeFileSync(path.join(tmp, "a.rs"), `fn main(){ let mut out=String::new(); let mut start:Option<u32>=None; let mut prev=0u32;
 for c in 128u32..=0x10FFFF { let a = char::from_u32(c).map_or(false,|ch| ch.is_alphanumeric());
  if a { if start.is_none(){start=Some(c);} } else if let Some(s)=start.take(){ out.push_str(&format!("{} {}\\n", s, c-1)); } let _=prev; prev=c; }
 if let Some(s)=start { out.push_str(&format!("{} {}\\n", s, 0x10FFFF)); } print!("{}", out); }`);
execFileSync("rustc", ["--edition", "2024", "-O", path.join(tmp, "a.rs"), "-o", path.join(tmp, "a")], { cwd: path.join(root, "vendor/bun") });
const alnumRanges = execFileSync(path.join(tmp, "a"), { cwd: path.join(root, "vendor/bun") }).toString().trim().split("\n").map((l) => l.split(" ").map(Number));
const ad = [];
prev = 0;
for (const [lo, hi] of alnumRanges) { ad.push(lo - prev, hi - lo); prev = hi; }

const q = JSON.stringify;
const out = `// GENERATED by tools/md/gen-tables.mjs from vendor/bun/src/md — do not edit.
// Compact encodings, decoded lazily by unicode.ts / entity.ts / helpers.ts.

/** Unicode punctuation+symbol ranges (md4c's punct map): base-36 deltas (lo - prevHi, hi - lo). ${pr.length} ranges. */
export const PUNCT_RANGES = ${q(enc(pd))};

/** Case folding maps 1..3: "<kind,cp,...>|<data...>" in base 36 (kind 0 single, 1 range start, 2 range end). */
export const FOLD_MAP_1 = ${q(folds[0])};
export const FOLD_MAP_2 = ${q(folds[1])};
export const FOLD_MAP_3 = ${q(folds[2])};

/** Names of the ${names.length} HTML entities (without the leading &, with the ;), sorted, concatenated. */
export const ENTITY_NAMES = ${q(names.join(""))};
/** Per entity: first codepoint, second codepoint or 0 (base 36). */
export const ENTITY_CODEPOINTS = ${q(enc(entCp))};

/** char::is_alphanumeric ranges >= 128 of the pinned Rust toolchain: base-36 deltas. ${alnumRanges.length} ranges. */
export const ALNUM_RANGES = ${q(enc(ad))};
`;
fs.writeFileSync(path.join(root, "src/md/tables.ts"), out);
console.log("wrote src/md/tables.ts", out.length, "bytes;", pr.length, "punct ranges,", alnumRanges.length, "alnum ranges");
