// Generates src/sema/messages.ts from vendor/bun/src/sema/messages.txt (TypeScript's diagnostic messages by code).
//   node tools/gen-messages.ts
import * as fs from "node:fs";
const text = fs.readFileSync("vendor/bun/src/sema/messages.txt", "utf8");
const codes: number[] = [];
const texts: string[] = [];
const cats: string[] = [];
for (const line of text.split("\n")) {
  if (line.length === 0) continue;
  const m = /^(\d+)\t(.)\t(.*)$/.exec(line);
  if (!m) throw new Error("bad line: " + line);
  codes.push(parseInt(m[1], 10));
  cats.push(m[2]);
  texts.push(m[3]);
}
let out = "// GENERATED by tools/gen-messages.ts from vendor/bun/src/sema/messages.txt. Do not edit.\n";
out += "// `bun_sema::messages`: TypeScript's diagnostic messages by code. `{0}`, `{1}`, ... are placeholders for the arguments.\n\n";
out += "const CODES: number[] = [" + codes.join(",") + "];\n";
out += "const IS_ERROR: string = " + JSON.stringify(cats.map((c) => (c === "E" ? "1" : "0")).join("")) + ";\n";
out += "const TEXTS: string = " + JSON.stringify(texts.join("\n")) + ";\n\n";
out += `let split: string[] | null = null;

/** The index of \`code\` in the table, or -1. */
function indexOf(code: number): number {
  let lo = 0;
  let hi = CODES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const c = CODES[mid];
    if (c === code) return mid;
    if (c < code) lo = mid + 1;
    else hi = mid - 1;
  }
  return -1;
}

/** The text of the message with \`code\` (\`{0}\` placeholders in it), or null. */
export function messageText(code: number): string | null {
  const at = indexOf(code);
  if (at < 0) return null;
  if (split === null) split = TEXTS.split("\\n");
  return split[at];
}

/** \`Message.Format\`: \`text\` with \`{n}\` replaced by \`args[n]\`. A placeholder without an argument is left unchanged. */
export function formatMessage(text: string, args: string[]): string {
  let out = "";
  let rest = text;
  for (;;) {
    const open = rest.indexOf("{");
    if (open < 0) break;
    let i = open + 1;
    let n = 0;
    while (i < rest.length) {
      const c = rest.charCodeAt(i);
      if (c < 48 || c > 57) break;
      n = n * 10 + (c - 48);
      i++;
    }
    if (i > open + 1 && i < rest.length && rest.charCodeAt(i) === 125 && n < args.length) {
      out += rest.slice(0, open) + args[n];
      rest = rest.slice(i + 1);
    } else {
      out += rest.slice(0, open + 1);
      rest = rest.slice(open + 1);
    }
  }
  return out + rest;
}

/** The message with \`code\` and \`args\`, or "Unexpected token" for a code that has none (what the formatter prints). */
export function diagnosticMessage(code: number, args: string[]): string {
  const text = messageText(code);
  if (text === null) return "Unexpected token";
  return formatMessage(text, args);
}
`;
fs.writeFileSync("src/sema/messages.ts", out);
console.log("messages", codes.length);
