// Writes tools/json/selftest-cases.ts: inputs (JSON, JSONC, JSON5, package.json, TOML) and what `bun fmt` makes of them.
//   node tools/json/gen-selftest.ts
import * as fs from "node:fs";
import * as os from "node:os";
import * as path from "node:path";
import { spawnSync } from "node:child_process";

type Case = { name: string; ext: string; input: string; config?: Record<string, unknown> };
const cases: Case[] = [
  { name: "object", ext: ".json", input: '{"a":1,"b":[1,2,3],"c":{"d":null}}' },
  { name: "long array", ext: ".json", input: '{"list":[' + Array.from({ length: 40 }, (_, i) => i * 1000).join(",") + ']}' },
  { name: "nested break", ext: ".json", input: '{"a":{"b":{"c":[{"d":1},{"e":2}]}},"s":"' + "x".repeat(70) + '"}' },
  { name: "empty", ext: ".json", input: "{}" },
  { name: "empty array", ext: ".json", input: "[ ]\n" },
  { name: "blank lines", ext: ".json", input: '{\n"a":1,\n\n\n"b":2,\n"c":[1,\n\n2]}' },
  { name: "preserved break", ext: ".json", input: '{\n"a":1}' },
  { name: "numbers", ext: ".json5", input: "[1.50, 0XAB, .5, 5., 1e+05, 1_000, +1, -.5, Infinity, -NaN]" },
  { name: "strings", ext: ".json", input: "{'a': 'it\\'s', \"b\": \"say \\\"x\\\"\", c: `t`}" },
  { name: "json5 names", ext: ".json5", input: '{"a":1,"b-c":2,\'d\':3, 4: 5}' },
  { name: "jsonc comments", ext: ".jsonc", input: '// top\n{\n  /* a */ "a": 1, // one\n  "b": [1, /* x */ 2],\n  // end\n}\n' },
  { name: "jsonc trailing commas", ext: ".jsonc", input: '{"a":[1,2,],"b":{"c":1,},}' },
  { name: "comments only", ext: ".jsonc", input: "// nothing\n" },
  { name: "holes", ext: ".json", input: "[1,,2,,]" },
  { name: "unicode", ext: ".json", input: '{"日本語":"😀 é","k":"a\\u00e9"}' },
  { name: "crlf", ext: ".json", input: '{\r\n"a":1,\r\n"b":[1,\r\n2]}\r\n' },
  { name: "bom", ext: ".json", input: '﻿{"a":1}' },
  { name: "stringify", ext: ".importmap", input: '{"a":[1,2,3],"b":{},"c":[],"d":`x`,"e":[,]}' },
  { name: "error: unclosed", ext: ".json", input: '{"a":' },
  { name: "error: token", ext: ".json", input: '{"a" 1}' },
  { name: "error: string", ext: ".json", input: '{"a":"x' },
  { name: "tabs and width", ext: ".json", input: '{"a":{"b":{"c":"' + "y".repeat(60) + '"}}}', config: { useTabs: true, tabWidth: 4, printWidth: 50 } },
  { name: "quote props preserve", ext: ".json5", input: '{"a":1,"b":2}', config: { quoteProps: "preserve", singleQuote: true } },
  { name: "toml basic", ext: ".toml", input: "a   = 1\n[tbl]\nb=[1,2,\n3]\nc = {x=1,y=2}\n# c\n" },
  { name: "toml long array", ext: ".toml", input: 'deps = ["' + Array.from({ length: 12 }, (_, i) => "package-" + i).join('", "') + '"]\n' },
  { name: "toml comments", ext: ".toml", input: "[a] # one\nb = [ # c\n 1, # d\n 2\n]\n\n\n\n[[c]]\nd = { e = 1 }\n" },
  { name: "toml crlf", ext: ".toml", input: "a = 1\r\n\r\n\r\n[b]\r\nc = [\r\n 1,\r\n 2]\r\n" },
  { name: "toml error", ext: ".toml", input: "a = \n" },
];

const BUN = os.homedir() + "/.bun/bin/bun";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "selft"));
let src = "// GENERATED by tools/json/gen-selftest.ts from `bun fmt`: do not edit.\n// [name, extension, input, options (name=value;...), expected output ('' with `error`: refused)]\nexport const SELFTEST_CASES: string[][] = [\n";
for (let i = 0; i < cases.length; i++) {
  const c = cases[i];
  const dir = `${root}/c${i}`;
  fs.mkdirSync(dir);
  if (c.config) fs.writeFileSync(dir + "/.prettierrc", JSON.stringify(c.config));
  const file = `${dir}/in${c.ext}`;
  fs.writeFileSync(file, c.input);
  const r = spawnSync(BUN, ["fmt", "."], { cwd: dir, encoding: "utf8" });
  const refused = /error:/.test(r.stderr);
  const out = refused ? "<error>" : fs.readFileSync(file, "utf8");
  src += `  [${JSON.stringify(c.name)}, ${JSON.stringify(c.ext)}, ${JSON.stringify(c.input)}, ${JSON.stringify(Object.entries(c.config ?? {}).map(([k, v]) => k + "=" + v).join(";"))}, ${JSON.stringify(out)}],\n`;
}
src += "];\n";
fs.writeFileSync(new URL("./selftest-cases.ts", import.meta.url).pathname, src);
fs.rmSync(root, { recursive: true, force: true });
console.log("ok", cases.length);
