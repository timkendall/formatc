// Generates src/format/html/data_tables.ts from vendor/bun/src/format/html/data.rs (run with node).
import { readFileSync, writeFileSync } from "node:fs";
const rs = readFileSync("vendor/bun/src/format/html/data.rs", "utf8");

function block(start: string): string {
  const i = rs.indexOf(start);
  if (i < 0) throw new Error("missing " + start);
  const j = rs.indexOf("\n];", i);
  return rs.slice(i, j);
}
// tag definitions
const defsBlock = block("const TAG_DEFINITIONS");
const defs: [string, string][] = [];
for (const m of defsBlock.matchAll(/\(key\(b"([^"]*)"\), &([A-Z_]+)\)/g)) defs.push([m[1], m[2]]);
// css display
const dispBlock = block("const CSS_DISPLAY_TAGS");
const disp: [string, string][] = [];
for (const m of dispBlock.matchAll(/\(key\(b"([^"]*)"\), Display::(\w+)\)/g)) disp.push([m[1], m[2]]);
// html tags / events
function list(start: string): string[] {
  const b = block(start);
  return [...b.matchAll(/b"([^"]*)"/g)].map((m) => m[1]);
}
const htmlTags = list("const HTML_TAGS");
const events = list("const HTML_EVENT_ATTRIBUTES");
// attributes of element
const i0 = rs.indexOf("fn attributes_of_element");
const attrsSrc = rs.slice(i0);
const attrs: [string, string[]][] = [];
for (const m of attrsSrc.matchAll(/((?:b"[^"]+"\s*\|\s*)*b"[^"]+")\s*=>\s*&\[([^\]]*)\]/g)) {
  const values = [...m[2].matchAll(/b"([^"]*)"/g)].map((x) => x[1]);
  for (const n of m[1].matchAll(/b"([^"]+)"/g)) attrs.push([n[1], values]);
}
let out = "// GENERATED by tools/html/gen-data.ts from vendor/bun/src/format/html/data.rs. Do not edit.\n\n";
out += `export const TAG_DEF_NAMES: string = ${JSON.stringify(defs.map((d) => d[0]).join(" "))};\n`;
out += `export const TAG_DEF_KINDS: string = ${JSON.stringify(defs.map((d) => d[1]).join(" "))};\n`;
out += `export const CSS_DISPLAY_NAMES: string = ${JSON.stringify(disp.map((d) => d[0]).join(" "))};\n`;
out += `export const CSS_DISPLAY_KINDS: string = ${JSON.stringify(disp.map((d) => d[1]).join(" "))};\n`;
out += `export const HTML_TAGS: string = ${JSON.stringify(htmlTags.join(" "))};\n`;
out += `export const HTML_EVENT_ATTRIBUTES: string = ${JSON.stringify(events.join(" "))};\n`;
out += `export const ELEMENT_ATTRIBUTE_ELEMENTS: string = ${JSON.stringify(attrs.map((a) => a[0]).join(" "))};\n`;
out += `export const ELEMENT_ATTRIBUTE_LISTS: string[] = ${JSON.stringify(attrs.map((a) => a[1].join(" ")))};\n`;
writeFileSync("src/format/html/data_tables.ts", out);
console.log(defs.length, disp.length, htmlTags.length, events.length, attrs.length);
